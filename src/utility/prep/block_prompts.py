"""
Block-specific prompt assembly for the cache-warmed parallel prep path.

Reuses ROLE / LOCALIZATION_POLICY / BLOCK_SCHEMA text straight out of
src/Deepseek/prompt/prep_prompt_deepseek_en.xml (the unified path's prompt) instead of
re-authoring 15 blocks' worth of instructions a second time — one drift
surface is enough. See PARALLEL_PREP_GUIDE.md §3 for why the system prompt
below must be byte-identical across EVERY call in a run, Pro's included: the
block-specific instruction is the one thing allowed to vary, so it lives
entirely in the user-turn's trailing <BLOCK_TASK>, never in <system>.

build_shared_system_prompt()/build_shared_prefix() below exist to test a
theory: if Pro's own Phase 1 call shares its leading bytes with every Phase
2 Flash call, the ~30-50K-token jp_chapters block might only need processing
fresh ONCE per prep run (by Pro) instead of twice.

Status: UNCONFIRMED, don't trust it. dev/test_cross_model_cache.py's Test B
(a throwaway system prompt) showed a Pro call cleanly warming a Flash call's
cache, first-ever exposure included — that's what motivated this. Test C
immediately after ran the identical cross-model check through these actual
functions (real ROLE+LOCALIZATION_POLICY system prompt, real task-suffix
text) and got a clean miss instead. No documented mechanism explains the
gap; treat the restructuring below as request-shape hygiene that MIGHT
occasionally save a fresh jp_chapters pass, not as a proven cost win. It
does not change correctness either way, and a sequential Flash warming call
is still required before the 12 parallel calls regardless of outcome.
"""

